def main() -> int:
    OUT.mkdir(parents=True, exist_ok=True)
    raw = V1.read_text(encoding="utf-8")
    lines = raw.split("\n")
    n0 = len(lines)
    report: dict = {"kind": "p6_en_v2_generation", "generated": time.strftime("%Y-%m-%dT%H:%M:%S%z"),
                    "source": str(V1.relative_to(REPO)),
                    "source_sha256": hashlib.sha256(V1.read_bytes()).hexdigest(),
                    "source_lines": n0, "edits": []}

    # ---- T1 头部（第 3–10 行，1-based）----
    assert lines[2].startswith("> **Draft status"), lines[2][:60]
    assert lines[9].strip().endswith("release authority is human."), lines[9][-40:]
    body_lines = lines[:2] + NEW_HEADER.split("\n") + lines[10:]
    report["edits"].append({"id": "T1_header", "lines_replaced": "3-10",
                            "old_lines": lines[2:10], "new_lines": NEW_HEADER.split("\n")})

    # ---- T2 摘要 ----
    text = "\n".join(body_lines)
    i0 = text.index("Multi-physics design-space exploration of piezoelectric")
    i1 = text.index("**Index Terms**")
    old_abs = text[i0:i1].rstrip("\n")
    wc = word_count(NEW_ABSTRACT)
    if wc > 150:
        raise SystemExit("摘要 %d 词 > 150，拒绝生成" % wc)
    text = text[:i0] + NEW_ABSTRACT + "\n\n" + text[i1:]
    report["edits"].append({"id": "T2_abstract", "old_words": word_count(old_abs),
                            "new_words": wc, "hard_limit": 150})

    # ---- T3 内部标签 ----
    tags = TAG_RE.findall(text)
    text, n_tag = TAG_RE.subn("", text)
    # 只清理**句中**因删标签产生的多余空格；**绝不触碰行首缩进**
    # （v1 的编号列表用 3 空格续行缩进，全局 collapse 会把列表结构改坏 —— 实测踩过）
    text = re.sub(r"(?<=\S) {2,}", " ", text)
    text = text.replace(" .", ".").replace(" ,", ",").replace(" ;", ";")
    # 句首标签被删后要补大写（否则出现 "). reports that ..." 这类语法破损）
    GRAMMAR = [("structural velocity). reports that in the source",
                "structural velocity). The source table reports that in the"),
               ("[C1] ", "[C1] ")]
    for old_g, new_g in GRAMMAR:
        if old_g in text and old_g != new_g:
            text = text.replace(old_g, new_g)
    # 行尾残留空格（标签在行尾被删后留下）：逐行 rstrip（v1 未使用"两空格硬换行"，故安全）
    text = "\n".join(l.rstrip() for l in text.split("\n"))
    report["edits"].append({"id": "T3_strip_provenance_tags", "removed": n_tag,
                            "distinct": sorted(set(tags)),
                            "kept_numeric_citations": sorted(set(re.findall(r"\[\d+\]", text))),
                            "indent_preserved": True,
                            "grammar_repairs": [g[1][:60] for g in GRAMMAR if g[0] != g[1]]})

    # ---- T4–T8 逐处替换 ----
    for (old, new, want, eid) in EDITS:
        got = text.count(old)
        if got != want:
            raise SystemExit("替换 %s 命中 %d 次（期望 %d）⇒ 拒绝生成；请核对原文" % (eid, got, want))
        text = text.replace(old, new)
        report["edits"].append({"id": eid, "hits": got, "old_head": old[:70].replace("\n", " "),
                                "new_head": new[:70].replace("\n", " ")})

    # ---- T9 §9 移出投稿件 ----
    j = text.index("## 9. Number provenance")
    prov_body = text[j:]
    text = text[:j].rstrip("\n") + "\n\n"

    # ---- T10 AI 章节 + 参考文献 ----
    refs = refs_block()
    text = text + AI_SECTION + "## References\n\n" + refs
    report["edits"].append({"id": "T9_T10_sections", "moved_out_lines": len(prov_body.split("\n")),
                            "n_references": len(re.findall(r"^\[\d+\]", refs, re.M))})

    V2.write_text(text, encoding="utf-8", newline="\n")

    # 内部溯源件（含 §9 与注册摘要）
    PROV.write_text(
        "# 内部溯源件（**不进投稿**）：英文稿 v2 的数字溯源与注册用摘要\n\n"
        "- 生成：%s；由 `work/tools/make_dac2027_en_v2.py` 从 v1 拆出（**正文数字一字未改**）。\n"
        "- 投稿候选：`docs/PAPER_DAC2027_EN_v2_20261011.md`（正文不含本文件内容）。\n"
        "- 为什么拆出：本件含仓库路径/文件名/sha256，**双盲与篇幅都不允许**出现在投稿件里。\n\n"
        "## A. Stage-1 注册摘要（DAC 2027 要求 *approximately 100 words*，2026-11-11 截止）\n\n"
        "> An abstention-aware surrogate flow for PMUT design-space exploration is presented and\n"
        "> stress-tested. Resonance-semantic labelling marks censored and unclosed labels; a layered\n"
        "> surrogate handles mixed continuous–discrete inputs; calibrated intervals are reported with\n"
        "> their empirical coverage; and out-of-domain queries are refused and referred back to the\n"
        "> finite-element solver. Evidence is reported per corpus, never pooled. Three results are\n"
        "> negative, including a physics-consistency gate that fails on energy closure. A\n"
        "> pre-registered fixed-budget closed loop reaches zero simple regret after five evaluations.\n\n"
        "（词数由脚本统计并写进生成报告；**若与系统字数上限冲突，以系统为准**。）\n\n"
        "## B. v1 §9 原文（数字溯源表，逐字保留）\n\n" + prov_body,
        encoding="utf-8", newline="\n")

    report["outputs"] = {
        str(V2.relative_to(REPO)): {"lines": text.count("\n") + 1,
                                    "bytes": V2.stat().st_size,
                                    "sha256": hashlib.sha256(V2.read_bytes()).hexdigest(),
                                    "words": word_count(text)},
        str(PROV.relative_to(REPO)): {"lines": PROV.read_text(encoding="utf-8").count("\n") + 1,
                                      "bytes": PROV.stat().st_size,
                                      "sha256": hashlib.sha256(PROV.read_bytes()).hexdigest()},
    }
    (OUT / "V2_GENERATION_REPORT.json").write_text(json.dumps(report, ensure_ascii=False, indent=2) + "\n",
                                                   encoding="utf-8")
    print("== 摘要：%d 词 → %d 词（≤150 ✓）" % (report["edits"][1]["old_words"], wc))
    print("== 去掉内部标签 %d 处：%s" % (n_tag, report["edits"][2]["distinct"]))
    print("== 保留数字引用：%s" % report["edits"][2]["kept_numeric_citations"])
    for e in report["edits"]:
        if e["id"].startswith("T") and "hits" in e:
            print("   %-4s 命中 %d" % (e["id"], e["hits"]))
    for k, v in report["outputs"].items():
        print("== 写出 %s (%d 行, %d B, %d 词)" % (k, v["lines"], v["bytes"], v.get("words", 0)))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
