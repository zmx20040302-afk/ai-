def word_count(s: str) -> int:
    return len(re.findall(r"[A-Za-z0-9][A-Za-z0-9'’\-\./%]*", s))


def refs_block() -> str:
    """从中文稿里抽**参考文献条目**（只取 `[n] …` 及其续行）。

    ⚠️ 实测踩坑：中文稿在参考文献**之后**还有中文小节；早先用"从'参考文献'到文件尾"的粗暴切片，
    结果把中文段落带进了英文投稿件（本脚本的 CJK 自检抓到）。这里改成状态机：
      * 以 `[数字]` 开头的行 → 条目开始/继续；
      * 空行 → 暂记为"可能结束"，**下一个非空行仍以 `[数字]` 开头则继续**；
      * 出现非 `[数字]` 开头的非空行且上一个非空行是空行 → **参考文献段结束**；
      * 遇到 `#`/`---` 标题行 → 立即结束。
    """
    t = io.open(ZH, encoding="utf-8").read()
    i = t.find("参考文献")
    if i < 0:
        raise SystemExit("中文稿里找不到参考文献段")
    lines = t[i + len("参考文献"):].split("\n")
    out: list[str] = []
    pending_blank = False
    started = False
    for ln in lines:
        s = ln.rstrip()
        if not s:
            pending_blank = bool(out)
            continue
        if s.startswith("#") or s.startswith("---"):
            break
        if re.match(r"^\[\d+\]", s):
            out.append(s)
            pending_blank = False
            started = True
            continue
        if pending_blank:
            break                      # 条目列表已被空行 + 非条目行终止
        if started:
            out.append(s)              # 续行（折行的条目）
    if not out:
        raise SystemExit("参考文献段解析为空")
    return "\n\n".join(out) + "\n"


