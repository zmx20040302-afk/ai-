def main() -> int:
    raw = V7.read_bytes()
    got = sha256(raw)
    if got != V7_SHA256 or len(raw) != V7_BYTES:
        print("FATAL v7 sha256/bytes mismatch: %s / %d" % (got, len(raw)))
        return 2
    if raw.count(b"\r\n") != V7_LINES or raw.count(b"\n") != V7_LINES:
        print("FATAL v7 not pure CRLF")
        return 2
    if raw.count(b"\r") != V7_LINES:
        print("FATAL v7 has lone CR")
        return 2

    text = raw.decode("utf-8")
    lines = text.split("\r\n")
    if len(lines) != V7_LINES + 1 or lines[-1] != "":
        print("FATAL v7 line split unexpected: %d" % len(lines))
        return 2

    # --- 占位符：把 __WHOLE_LINE__ 展开为「整行逐字」 ---
    repl: list[tuple[int, str, str]] = []
    for lineno, old, new in REPL:
        if old == "__WHOLE_LINE__":
            old = lines[lineno - 1]
            if old in text and text.count(old) != 1:
                print("FATAL whole-line old not unique in document: line %d count=%d"
                      % (lineno, text.count(old)))
                return 2
        repl.append((lineno, old, new))

    # --- 校验：每条旧片段在其所在行恰好 1 次、全稿恰好 1 次 ---
    per_line: dict[int, list[tuple[str, str]]] = {}
    for lineno, old, new in repl:
        if not (1 <= lineno <= V7_LINES):
            print("FATAL lineno out of range: %d" % lineno)
            return 2
        line = lines[lineno - 1]
        if line.count(old) != 1:
            print("FATAL old not unique in line %d: count=%d" % (lineno, line.count(old)))
            print("  OLD:", old[:120])
            return 2
        if text.count(old) != 1:
            print("FATAL old not unique in document: line=%d count=%d" % (lineno, text.count(old)))
            return 2
        if new in text:
            print("FATAL new already present in v7 (line %d): %s" % (lineno, new[:120]))
            return 2
        per_line.setdefault(lineno, []).append((old, new))

    # --- 校验：同一行内片段互不重叠 ---
    for lineno, items in per_line.items():
        line = lines[lineno - 1]
        spans = []
        for old, _ in items:
            i = line.index(old)
            spans.append((i, i + len(old)))
        spans.sort()
        for a, b in zip(spans, spans[1:]):
            if b[0] < a[1]:
                print("FATAL overlapping snippets in line %d: %s" % (lineno, spans))
                return 2

    # --- 应用替换 + 插入（并记录 v7 行 → v8 行段的映射，供逐字节反向还原） ---
    ins_after: dict[int, list[str]] = {}
    for lineno, newlines in INSERT:
        if not (1 <= lineno <= V7_LINES):
            print("FATAL insert lineno out of range: %d" % lineno)
            return 2
        ins_after.setdefault(lineno, []).extend(newlines)

    out_lines: list[str] = []
    layout: list[tuple[int, list[str], int]] = []   # (v7 行号, 该行的 own 行段, 插入行数)
    for idx, line in enumerate(lines[:-1], start=1):
        for old, new in per_line.get(idx, []):
            line = line.replace(old, new)
        own = line.split("\r\n")
        extra = ins_after.get(idx, [])
        out_lines.extend(own)
        out_lines.extend(extra)
        layout.append((idx, own, len(extra)))
    out_lines.append("")  # 结尾 CRLF

    v8_bytes = "\r\n".join(out_lines).encode("utf-8")

    # --- 校验：每条新片段在结果中恰好 1 次（非空行级插入行至少出现 1 次） ---
    v8_text = v8_bytes.decode("utf-8")
    for lineno, old, new in repl:
        for part in new.split("\r\n"):
            if part == "":
                continue
            c = v8_text.count(part)
            if c < 1:
                print("FATAL new part missing (line %d): %s" % (lineno, part[:120]))
                return 2
        c = v8_text.count(new)
        if c != 1:
            print("FATAL new count != 1 (line %d): %d" % (lineno, c))
            print("  NEW:", new[:160])
            return 2
    for _, newlines in INSERT:
        for nl in newlines:
            if nl == "":
                continue          # 空行允许重复（可逆性由「按位置反向还原」保证）
            if v8_text.count(nl) < 1:
                print("FATAL inserted line missing: %s" % nl[:160])
                return 2

    # --- 校验：纯 CRLF ---
    n_lf = v8_bytes.count(b"\n")
    n_crlf = v8_bytes.count(b"\r\n")
    n_cr = v8_bytes.count(b"\r")
    if n_lf != n_crlf or n_cr != n_crlf:
        print("FATAL v8 not pure CRLF: LF=%d CRLF=%d CR=%d" % (n_lf, n_crlf, n_cr))
        return 2

    # --- 校验：反向还原可逐字节还原 v7（**按位置**逐行回退，支持多行替换与空行插入） ---
    r_lines = v8_text.split("\r\n")[:-1]
    expect_total = sum(len(own) + n_ins for _, own, n_ins in layout)
    if len(r_lines) != expect_total:
        print("FATAL reverse: line count %d != expected %d" % (len(r_lines), expect_total))
        return 2
    back: list[str] = []
    pos = 0
    for idx, own, n_ins in layout:
        seg = r_lines[pos:pos + len(own)]
        pos += len(own) + n_ins          # 跳过本行的插入行
        line = "\r\n".join(seg)
        for old, new in per_line.get(idx, []):
            if line.count(new) != 1:
                print("FATAL reverse: new not unique in line %d (count=%d)" % (idx, line.count(new)))
                return 2
            line = line.replace(new, old)
        back.append(line)
    if pos != len(r_lines):
        print("FATAL reverse: leftover %d lines" % (len(r_lines) - pos))
        return 2
    back.append("")
    restored = "\r\n".join(back).encode("utf-8")
    if restored != raw:
        print("FATAL reverse restore != v7 (byte-level)")
        return 2

    # --- 写盘 ---
    V8.write_bytes(v8_bytes)

    cp = 0
    for a, b in zip(raw, v8_bytes):
        if a != b:
            break
        cp += 1

    print("V8_OK")
    print("v7: %d B / %d 行(CRLF) / %s" % (len(raw), V7_LINES, sha256(raw)))
    print("v8: %d B / %d CRLF / %d 行(read 口径) / %s"
          % (len(v8_bytes), v8_bytes.count(b"\r\n"), v8_text.count("\n"), sha256(v8_bytes)))
    print("path: %s" % V8)
    print("replacements: %d  inserts: %d" % (len(repl), sum(len(v) for _, v in INSERT)))
    print("common_prefix_bytes: %d (v7 不是 v8 的字节前缀)" % cp)
    print("reverse_restore == v7: True")
    return 0


