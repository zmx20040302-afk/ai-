wc = lambda s: len(re.findall(r"[A-Za-z0-9][A-Za-z0-9'’\-\./%]*", s))


def block(start_key: str, end_key: str, label: str) -> None:
    i = t.find(start_key)
    j = t.find(end_key, i + 1)
    if i < 0 or j < 0:
        print("%-52s 定位失败" % label)
        return
    print("%-52s %4d 词" % (label, wc(t[i:j])))


