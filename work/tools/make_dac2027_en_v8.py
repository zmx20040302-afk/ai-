"""v8：由 **v7** 生成 —— 把 §6.4 末段（场级 ROM）移出正文，内容保留在补充材料 §S10。

依据：用户 2026-10-12 裁定「先把场级 ROM 段移入补充材料」（INDEX §213 第四条）。
做法：**定位并删除该整段**（用起止标记定位，不用手抄长字符串），并在前一句末尾加**一句指针**。
其余一字不动；**LF**；报告哈希**从磁盘字节算**（与 v7 生成器同样的纪律）。

产物：`docs/PAPER_DAC2027_EN_v8_20261012.md`、`docs/PAPER_DAC2027_EN_v8_PROVENANCE.md`、
      `work/runs/eda64-20261010/n5_stage3/V8_GENERATION_REPORT.json`
"""
from __future__ import annotations

import hashlib
import json
import pathlib
import sys
import time

sys.stdout.reconfigure(encoding="utf-8", errors="replace")
REPO = pathlib.Path(__file__).resolve().parents[2]
V7 = REPO / "docs/PAPER_DAC2027_EN_v7_20261012.md"
V8 = REPO / "docs/PAPER_DAC2027_EN_v8_20261012.md"
V8P = REPO / "docs/PAPER_DAC2027_EN_v8_PROVENANCE.md"
SUP = REPO / "docs/PAPER_DAC2027_EN_SUPPLEMENT_20261012.md"
OUT = REPO / "work/runs/eda64-20261010/n5_stage3"

START = "\n\n**The field-level obstruction is physical, not methodological.**"
ANCHOR = "Per-check tables, the ladder history and the full caveat list are in §S2–§S5."
POINTER = "Per-check tables, the ladder history and the full caveat list are in §S2–§S5; the field-level representation study is in §S10."


def main() -> int:
    v7 = V7.read_text(encoding="utf-8")
    v7_sha = hashlib.sha256(V7.read_bytes()).hexdigest()
    if "\r\n" in v7:
        raise SystemExit("[FAIL] v7 含 CRLF（预期纯 LF）")
    if v7.count(START) != 1:
        raise SystemExit("[FAIL] E 段起点标记命中 %d 次（要求 1）" % v7.count(START))
    if v7.count(ANCHOR) != 1:
        raise SystemExit("[FAIL] 指针锚点命中 %d 次（要求 1）" % v7.count(ANCHOR))

    i = v7.find(START)
    j = v7.find("\n\n", i + 2)                     # 该段结束（下一处空行）
    if j < 0:
        raise SystemExit("[FAIL] 找不到 E 段结束位置")
    para = v7[i:j]
    if "§S10" not in para:
        raise SystemExit("[FAIL] 待删段内未出现 §S10（疑似定位错）")
    if "The field-level obstruction" not in para:
        raise SystemExit("[FAIL] 待删段内容不符")
    v8 = v7[:i] + v7[j:]                            # 删段
    v8 = v8.replace(ANCHOR, POINTER)                # 加一句指针

    # 守卫
    if "The field-level obstruction" in v8:
        raise SystemExit("[FAIL] v8 仍含 E 段")
    if "§S10" not in v8:
        raise SystemExit("[FAIL] v8 丢失 §S10 指针")
    if len(v8) >= len(v7):
        raise SystemExit("[FAIL] v8 未变短")

    v8_bytes = v8.encode("utf-8")
    V8.write_bytes(v8_bytes)                        # **写字节** ⇒ 保持 LF

    # 回读自检（真实校验）
    disk = V8.read_text(encoding="utf-8")
    disk_bytes = V8.read_bytes()
    if b"\r\n" in disk_bytes:
        raise SystemExit("[FAIL] v8 出现 CRLF")
    # 反向还原：把指针换回锚点、并把段落插回原位置 ⇒ 应逐字节还原 v7
    k = disk.find(POINTER)
    if k < 0:
        raise SystemExit("[FAIL] 回读后找不到指针")
    back = disk[:k] + ANCHOR + para + disk[k + len(POINTER):]
    if back != v7:
        raise SystemExit("[FAIL] 往返校验失败：还原后与 v7 不一致")

    wc = lambda s: len([w for w in __import__("re").findall(r"[A-Za-z0-9][A-Za-z0-9'’\-\./%]*",
                                                            s[:s.find("## Content Generated by AI")])])
    w7, w8 = wc(v7), wc(disk)
    sup_bytes = SUP.read_bytes()
    rep = {"kind": "dac2027_en_v8_generation", "generated": time.strftime("%Y-%m-%dT%H:%M:%S"),
           "source": V7.name, "source_sha256": v7_sha, "source_bytes": len(V7.read_bytes()),
           "removed_paragraph_chars": len(para), "pointer_added_chars": len(POINTER) - len(ANCHOR),
           "output": V8.name, "output_sha256": hashlib.sha256(disk_bytes).hexdigest(),
           "output_bytes": len(disk_bytes), "output_eol": "LF",
           "supplement_unchanged": SUP.name,
           "supplement_sha256": hashlib.sha256(sup_bytes).hexdigest(),
           "body_words_v7": w7, "body_words_v8": w8, "body_words_delta": w8 - w7,
           "roundtrip_restores_v7": True,
           "page_note": "§6.4 末段已移出正文；内容留在补充材料 §S10。A/C/D1 三处正确性更正**未动**。"}
    if hashlib.sha256(V8.read_bytes()).hexdigest() != rep["output_sha256"]:
        raise SystemExit("[FAIL] 报告哈希与磁盘不一致")
    OUT.mkdir(parents=True, exist_ok=True)
    (OUT / "V8_GENERATION_REPORT.json").write_bytes(
        (json.dumps(rep, ensure_ascii=False, indent=2) + "\n").encode("utf-8"))

    V8P.write_bytes(f"""# v8 出处说明（DAC 2027 英文稿）

- 生成：{time.strftime("%Y-%m-%d")}；由 **v7**（`{V7.name}`，sha256 `{v7_sha[:24]}`，
  {len(V7.read_bytes())} B）**删除 §6.4 末段（场级 ROM，{len(para)} 字符）**并加入一句指针生成。
- 产物：`{V8.name}`（sha256 `{rep["output_sha256"][:24]}`，{rep["output_bytes"]} B，**LF**）。
- 补充材料**未改**：`{SUP.name}`（sha256 `{rep["supplement_sha256"][:24]}`）—— 场级 ROM 的完整内容在 **§S10**。
- 正文词数：v7 **{w7}** → v8 **{w8}**（{w8 - w7:+d}）。
- **生成自检**：从磁盘回读；**把指针换回锚点、并把该段插回原位置 ⇒ 逐字节还原 v7**（证明只动了这一处）；
  守卫：v8 不得仍含该段、不得丢 §S10 指针、不得出现 CRLF、报告哈希须等于磁盘.

## 依据与边界

- 依据：用户 2026-10-12 裁定「先把场级 ROM 段移入补充材料」（INDEX §213）。
- 理由：该段讲的是**场级** ROM，与本文主贡献（**通道级**代理 + 筛选器定位）不是同一条线；
  §6.4 是版面最紧的一节。
- **未动**：A（S3 计数更正）/ C（§6.5 表行改写）/ D1（S4「跑前冻结」）三处正确性更正，以及 B（两口径）段。

## 页数

DAC 限 **6 页 + 1 页仅参考文献**；本机**无 TeX**，**页数仍未编译验证**。若仍溢出，
下一批删减对象：§6.5 两口径段 → §6.5 末句（S4 非独立性）→ §3/§6.1–6.3 叙述。

## 不主张

- **不主张** v8 满足 6 页；**不主张** v8 已可提交；**不改任何数字**；**不改任何图表**；
- 不提升任何状态；`release_allowed` 仍 `false`；`solver_spec` 仍 `draft`。
""".encode("utf-8"))

    print("v7 %d B（sha %s）→ v8 %d B（sha %s）" % (rep["source_bytes"], v7_sha[:16],
                                                  rep["output_bytes"], rep["output_sha256"][:16]))
    print("删除段落 %d 字符；加指针 +%d 字符" % (len(para), len(POINTER) - len(ANCHOR)))
    print("正文词数 v7 %d → v8 %d（%+d）" % (w7, w8, w8 - w7))
    print("自检：回读 + 往返还原 v7 通过；守卫（无残留段/有 §S10/无 CRLF/哈希一致）通过")
    print("写出:", V8.name, "|", V8P.name, "| V8_GENERATION_REPORT.json")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
