sys.stdout.reconfigure(encoding="utf-8", errors="replace")
REPO = pathlib.Path(__file__).resolve().parents[2]
V15 = REPO / "docs/PAPER_DAC2027_EN_v15_20261013.md"
V16 = REPO / "docs/PAPER_DAC2027_EN_v16_20261013.md"
V16P = REPO / "docs/PAPER_DAC2027_EN_v16_PROVENANCE.md"
SUP = REPO / "docs/PAPER_DAC2027_EN_SUPPLEMENT_20261013c.md"
OUT = REPO / "work/runs/eda64-20261010/n5_stage3"
MAN = REPO / "work/dist/peakguard-bench-v1-20261013/MANIFEST.json"

C3_OLD = ("   splits with five seeds, reporting the channels that gain nothing instead of a pooled score.\n"
          "4. **C4 — physics-consistency gates")
C3_NEW = ("   splits with five seeds, reporting the channels that gain nothing instead of a pooled score. The corpus,\n"
          "   the frozen split, the thresholds and the evaluation code are released as a self-contained package.\n"
          "4. **C4 — physics-consistency gates")

