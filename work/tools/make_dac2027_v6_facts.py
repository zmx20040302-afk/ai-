def _lf(s: str) -> str:
    return s.replace("\r\n", "\n")


def main() -> int:
    raw_v5 = V5.read_bytes()
    got = hashlib.sha256(raw_v5).hexdigest()
    if got != V5_SHA:
        print("[FAIL] v5 基线 sha256 不符：%s != %s" % (got, V5_SHA))
        return 2
    dec = raw_v5.decode("utf-8")
    if dec.count("\n") != dec.count("\r\n"):
        print("[FAIL] v5 非纯 CRLF（%d LF / %d CRLF）" % (dec.count("\n"), dec.count("\r\n")))
        return 2
    text = _lf(dec)                      # 在 LF 归一文本上做替换

    # 唯一性守卫
    for label, old, _new in R:
        n = text.count(old)
        if n != 1:
            print("[FAIL] %s：旧片段出现 %d 次（要求恰好 1 次）" % (label, n))
            if n == 0:
                print("       片段前 60 字：%r" % old[:60])
            return 2
    # 互不重叠
    spans = sorted((text.index(old), text.index(old) + len(old), label) for label, old, _ in R)
    for a, b in zip(spans, spans[1:]):
        if b[0] < a[1]:
            print("[FAIL] 片段重叠：%s 与 %s" % (a[2], b[2]))
            return 2
    new_text = text
    for _label, old, new in R:
        new_text = new_text.replace(old, _lf(new), 1)

    # 反向还原占位检查：每条新片段在结果中必须恰好出现 1 次，否则反向替换有歧义
    for label, _old, new in R:
        n = new_text.count(_lf(new))
        if n != 1:
            print("[FAIL] %s：新片段在结果中出现 %d 次（反向还原会有歧义）" % (label, n))
            return 2

    # 转回纯 CRLF
    out_text = new_text.replace("\n", "\r\n")
    if out_text.count("\n") != out_text.count("\r\n"):
        print("[FAIL] 归一后仍有裸 LF")
        return 2

    # 逐字节最强守卫：换回旧片段应还原 v5（LF 归一文本上比对）
    back = new_text
    for _label, old, new in R:
        back = back.replace(_lf(new), old, 1)
    if back != text:
        print("[FAIL] 反向还原失败 —— 除登记改动外还有其它差异")
        return 2

    if V6.is_file():
        # 就地改守卫（`INDEX §131.2`）：重跑时 V6 已存在 ⇒ 先备份改前字节。
        backup_before_edit(V6)
    V6.write_bytes(out_text.encode("utf-8"))
    out = V6.read_bytes()
    print("v5 基线   = %s（%d B / %d 行 / %d CRLF）" % (
        got, len(raw_v5), dec.count("\n") + 1, dec.count("\r\n")))
    print("v6 写入   = %s（%d B / %d 行 / %d CRLF）" % (
        hashlib.sha256(out).hexdigest(), len(out),
        out.decode("utf-8").count("\n") + 1, out.decode("utf-8").count("\r\n")))
    print("改动条数 = %d" % len(R))
    # v6 是就地外科式修订（非 append-only）⇒ v5 不是 v6 的字节前缀；如实报告公共前缀长度
    cp = 0
    for x, y in zip(raw_v5, out):
        if x != y:
            break
        cp += 1
    print("v5 是 v6 的字节前缀 = %s（公共前缀 %d / %d B）" % (out.startswith(raw_v5), cp, len(raw_v5)))
    return 0


if __name__ == "__main__":
    sys.exit(main())
