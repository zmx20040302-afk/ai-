from __future__ import annotations

import io
import pathlib
import re
import sys

sys.stdout.reconfigure(encoding="utf-8", errors="replace")
REPO = pathlib.Path(__file__).resolve().parents[2]
T = io.open(REPO / "docs/PAPER_DAC2027_EN_v5_20261011.md", encoding="utf-8").read()
BODY = T[: T.find("## Content Generated by AI")]


def wc(s: str) -> int:
    return len(re.findall(r"[A-Za-z0-9][A-Za-z0-9'’\-\./%]*", s))


parts = re.split(r"(?m)^(#{2,3} .*)$", BODY)
cur, rows = "(前言)", []
for p in parts:
    if re.match(r"^#{2,3} ", p or ""):
        rows.append([p.strip(), 0])
    elif rows:
        rows[-1][1] += wc(p or "")
    else:
        rows.append([cur, wc(p or "")])
for h, w in rows:
    print("%6d  %s" % (w, h[:90]))
print("---- 正文合计 %d 词（含表格与公式内的词）" % wc(BODY))
