# -*- coding: utf-8 -*-
"""量 v13 的分节词数与候选削减块的词数，供页数预算裁定使用（只读）。"""
from __future__ import annotations

import pathlib
import re
import sys

sys.stdout.reconfigure(encoding="utf-8", errors="replace")
REPO = pathlib.Path(__file__).resolve().parents[2]
V = REPO / "docs/PAPER_DAC2027_EN_v13_20261013.md"
t = V.read_text(encoding="utf-8")
ai = t.find("## Content Generated by AI")
body_all = t[:ai]
refs = t[t.find("## References"):] if "## References" in t else ""


def wc(s: str) -> int:
    return len(re.findall(r"[A-Za-z0-9][A-Za-z0-9'’\-\./%]*", s))


# 按 "## n." / "### n.m" 切
marks = [(m.start(), m.group(0).strip()) for m in re.finditer(r"(?m)^#{2,3} [0-9]+(\.[0-9]+)?[ .]", t)]
print("总词数：正文(到 AI 段) %d ；AI+其后 %d ；含全部 %d" % (wc(body_all), wc(t[ai:]), wc(t)))
print()
print("%-42s %6s %6s" % ("节", "词数", "占比"))
for i, (pos, name) in enumerate(marks):
    end = marks[i + 1][0] if i + 1 < len(marks) else len(t)
    seg = t[pos:end]
    if wc(seg) > 0:
        print("%-42s %6d %5.1f%%" % (name[:42], wc(seg), 100.0 * wc(seg) / wc(t)))
print()
print("== 候选削减块词数（逐块实测） ==")
cands = [
    ("S4 段·fresh re-solve 三句",
     "A **fresh re-solve** of the same ladder (same model, same mesh) returns the same verdict but is **not bit-identical**"),
    ("S4 段·字节锚点+同解场两句",
     "The 2026-10-12 re-analysis froze the caliber and every byte anchor"),
    ("§6.5 探针表（7 行表格）", "| candidate cause | measurement | verdict |"),
    ("§6.5 表前一句+表后归因一大段", "We probed S3's energy item directly"),
    ("§6.4 S3 段（本版新增）", "**S3 passes — but only under two calibers signed by the reviewer.**"),
    ("§6.4 S0 段（本版新增）", "**S0 passes under a pre-registered protocol"),
]
for label, anchor in cands:
    i = t.find(anchor)
    if i < 0:
        print("%-38s 锚点未找到" % label)
        continue
    print("%-38s 锚点在 offset %6d（本块总词数请看该节）" % (label, i))
# 具体块：按段落取样
paras = [p for p in t.split("\n\n") if p.strip()]
for label, key in (("S4 段整段", "**S1/S2/S5 at the local level"),
                   ("§6.5 归因段（The calibrated statement…）", "The calibrated statement is therefore"),
                   ("§6.5 两口径段", "**Two calibers must be kept apart.**"),
                   ("§6.5 表段", "| candidate cause |"),
                   ("§3 全节", "## 3. Problem Definition")):
    hit = [p for p in paras if key in p]
    if hit:
        print("%-44s %5d 词" % (label, wc(hit[0])))
    else:
        print("%-44s 未按段落命中" % label)
