# -*- coding: utf-8 -*-
"""P6 复核：把 v1→v2 的**全部差异**逐行打出来（只读）。

用途：生成器改了什么必须**人可复核**；尤其要确认「去标签」没有把句子改坏
（多余空格、丢词、括号失配）。本脚本不写任何文件。
"""
from __future__ import annotations

import difflib
import io
import pathlib
import re
import sys

sys.stdout.reconfigure(encoding="utf-8", errors="replace")
REPO = pathlib.Path(__file__).resolve().parents[2]
a = io.open(REPO / "docs/PAPER_DAC2027_EN_v1_20261010.md", encoding="utf-8").read().split("\n")
b = io.open(REPO / "docs/PAPER_DAC2027_EN_v2_20261011.md", encoding="utf-8").read().split("\n")

# 只看"正文"（去掉新增的 AI 段与参考文献段，它们整段是新增）
cut = next(i for i, l in enumerate(b) if l.startswith("## Content Generated by AI"))
b_body = b[:cut]

sm = difflib.SequenceMatcher(a=a, b=b_body, autojunk=False)
n_changed = 0
for tag, i1, i2, j1, j2 in sm.get_opcodes():
    if tag == "equal":
        continue
    n_changed += 1
    print("### %s  v1[%d:%d] → v2[%d:%d]" % (tag, i1 + 1, i2, j1 + 1, j2))
    for l in a[i1:i2][:12]:
        print("   - %s" % l[:160])
    if i2 - i1 > 12:
        print("   - ...（共 %d 行）" % (i2 - i1))
    for l in b_body[j1:j2][:12]:
        print("   + %s" % l[:160])
    if j2 - j1 > 12:
        print("   + ...（共 %d 行）" % (j2 - j1))
    print()

print("== 差异块 %d 个；v1 %d 行 / v2 正文 %d 行" % (n_changed, len(a), len(b_body)))

# 健康检查：括号配平、双空格、残留标签、内部路径
txt = "\n".join(b_body)
print("\n== 健康检查（v2 正文）")
print("   残留内部标签 :", sorted(set(re.findall(r"\[(?!\d+\])(?=[A-Za-z])[A-Za-z][A-Za-z0-9\-]*\]", txt))))
print("   仓库路径      :", sorted(set(re.findall(r"work[/\\]runs\S*", txt)))[:5] or "无")
print("   sha256 字样   :", len(re.findall(r"sha256", txt)))
print("   双空格行数    :", sum(1 for l in b_body if "  " in l))
print("   空行里带空格  :", sum(1 for l in b_body if l != l.rstrip()))
print("   数字引用      :", sorted(set(re.findall(r"\[\d+\]", txt)), key=lambda s: int(s[1:-1])))
print("   圆括号配平    :", txt.count("(") - txt.count(")"))
