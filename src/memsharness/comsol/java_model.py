def default_values(template: TemplateSpec) -> dict[str, float]:
    return {p.name: p.default for p in template.params}


def validate_values(template: TemplateSpec, values: dict[str, float]) -> dict[str, float]:
    """校验参数：必须全部已知、数值有限、在声明区间内。不合法直接报错，不做默认填充。"""
    unknown = sorted(set(values) - set(template.param_names))
    if unknown:
        raise ValueError(f"模板 {template.name} 不认识的参数：{unknown}")
    merged = default_values(template)
    merged.update(values)
    for spec in template.params:
        raw = merged[spec.name]
        try:
            number = float(raw)
        except (TypeError, ValueError) as exc:
            raise ValueError(f"参数 {spec.name}={raw!r} 不是数值") from exc
        if not math.isfinite(number):
            raise ValueError(f"参数 {spec.name}={raw!r} 不是有限数")
        if spec.min_value is not None and number < spec.min_value:
            raise ValueError(f"参数 {spec.name}={number} 小于下界 {spec.min_value}")
        if spec.max_value is not None and number > spec.max_value:
            raise ValueError(f"参数 {spec.name}={number} 大于上界 {spec.max_value}")
        merged[spec.name] = number
    return merged


def render_source(template_name: str, values: dict[str, float]) -> tuple[str, dict[str, float]]:
    """返回 (Java 源码, 校验后的完整参数快照)。"""
    template = get_template(template_name)
    resolved = validate_values(template, values)
    return template.render(resolved), resolved


def analytic_values(template_name: str, values: dict[str, float]) -> dict[str, float]:
    template = get_template(template_name)
    return template.analytic(validate_values(template, values))


