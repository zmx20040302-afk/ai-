def _num(value: float) -> str:
    """把浮点数渲染成 Java 字面量（保证可逆、无千分位、无科学计数歧义）。"""
    if not math.isfinite(value):
        raise ValueError(f"参数值必须是有限数，收到 {value!r}")
    return repr(float(value))


def render_heat_slab_2d(values: dict[str, float]) -> str:
    """渲染 heat_slab_2d 的 Java 源码。"""
    subs = {
        "@@EXTRACTOR@@": EXTRACTOR_VERSION,
        "@@CLASS@@": "heat_slab_2d",
        "@@LX@@": _num(values["Lx"]),
        "@@LY@@": _num(values["Ly"]),
        "@@K@@": _num(values["k_cond"]),
        "@@RHO@@": _num(values["rho_mat"]),
        "@@CP@@": _num(values["Cp_mat"]),
        "@@T0@@": _num(values["T0"]),
        "@@QIN@@": _num(values["q_in"]),
        "@@HMAX@@": _num(values["hmax_mesh"]),
        "@@BND_T@@": str(int(values["bnd_t"])),
        "@@BND_Q@@": str(int(values["bnd_q"])),
        "@@RESULT_MARKER@@": RESULT_MARKER,
        "@@SAVED_MARKER@@": SAVED_MARKER,
        "@@DONE_MARKER@@": DONE_MARKER,
    }
    source = _JAVA_TEMPLATE
    for token, text in subs.items():
        source = source.replace(token, text)
    if "@@" in source:
        leftover = sorted(set(re.findall(r"@@[A-Z_]+@@", source)))
        raise ValueError(f"Java 模板存在未替换占位符：{leftover}")
    return source


def analytic_heat_slab_2d(values: dict[str, float]) -> dict[str, float]:
    """heat_slab_2d 的闭式解：T_max = T0 + q_in*Lx/k。

    这是**解析值**，不是仿真值；入库时必须以 ``source_type="analytic"`` 单独成条，
    严禁与仿真值合并（红线 4）。
    """
    t_max = values["T0"] + values["q_in"] * values["Lx"] / values["k_cond"]
    t_min = values["T0"]
    return {"T_max_K": t_max, "T_min_K": t_min}


