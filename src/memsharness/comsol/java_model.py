_JSON_OBJECT_RE = re.compile(r"\{.*\}")


def parse_result_marker(text: str) -> tuple[dict[str, Any] | None, str | None]:
    """从日志文本中解析 ``MEMS_RESULT_JSON=`` 标记。

    返回 ``(结果字典 或 None, 失败原因 或 None)``。解析不到就如实返回原因，
    绝不返回空字典冒充「成功但没数据」。
    """
    if not text:
        return None, "日志为空，未找到结果标记"
    line = None
    for raw in text.splitlines():
        if RESULT_MARKER in raw:
            # 只取标记之后的部分，避免前缀里的杂字符
            line = raw.split(RESULT_MARKER, 1)[1].strip()
    if line is None:
        return None, f"日志中没有 {RESULT_MARKER} 标记（可能求解或抽取阶段失败）"
    match = _JSON_OBJECT_RE.search(line)
    if not match:
        return None, f"标记后不是合法 JSON 对象：{line[:200]!r}"
    try:
        payload = json.loads(match.group(0))
    except json.JSONDecodeError as exc:
        return None, f"标记后的 JSON 解析失败：{exc}"
    if not isinstance(payload, dict):
        return None, "标记后的 JSON 不是对象"
    return payload, None


_FACT_PATTERNS: tuple[tuple[str, str], ...] = (
    ("elements", r"Number of elements\s*:?\s*(\d+)"),
    ("dof", r"Degrees of freedom\s*:?\s*(\d+)"),
    ("vertices", r"Number of vertices\s*:?\s*(\d+)"),
)


def parse_batchlog_facts(text: str) -> dict[str, Any]:
    """从 comsolbatch 日志里抽取可由日志直接读到的求解事实（网格/自由度）。

    读不到就是 ``None``（附原因），不猜测。
    """
    facts: dict[str, Any] = {}
    for key, pattern in _FACT_PATTERNS:
        match = re.search(pattern, text or "", re.IGNORECASE)
        facts[key] = int(match.group(1)) if match else None
    facts["missing_reason"] = [
        key for key, value in facts.items() if value is None and key != "missing_reason"
    ]
    return facts


def write_source(path: Path, source: str) -> Path:
    """写 Java 源码（强制 ASCII，防止代码页问题）。"""
    source.encode("ascii")  # 非 ASCII 直接抛错，不静默转码
    path.write_text(source, encoding="ascii", newline="\n")
    return path
