"""COMSOL Java API 参数化模型模板：生成源码 → 编译 → 批处理求解 → 抽取标量结果。

本条通路（``comsolcompile.exe`` + ``comsolbatch.exe``）**不依赖 MATLAB**；
LiveLink/MATLAB 通路留到以后（WORKING_PLAN 4.1 通路 A）。

实测事实（2026-06，本机 COMSOL 6.4，命令输出见 work/runs/*/commands.json）：
- ``comsolcompile -h``：`Example: comsolcompile file.java`，把模型 Java 文件编译为 class。
- ``comsolbatch -h``：``-inputfile <filename>  The input-file name (.mph or .class)``，
  ``-outputfile``、``-batchlog``、``-stoptime`` 可用。

生成策略：
- 每个参数点生成**一份独立的 Java 源码**，参数值直接以字面量写入，便于逐点复现与审计。
- Java 源码**全 ASCII**（英文注释），避免 javac 在中文 Windows 的 GBK 代码页下解析失败。
- Java 不接收任何外部路径：``model.save("out.mph")`` 写相对路径，由调用方把工作目录设为
  run 目录。这样绕开「中文路径 + 命令行参数编码」的不确定性。
- 求解结果通过 stdout 上的一行 ``MEMS_RESULT_JSON=...`` 标记回传，便于日志审计；
  解析失败的字段写 ``null`` 并记录原因，绝不臆测。
"""

